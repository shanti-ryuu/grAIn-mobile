function escapeHtml(value: unknown): string {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function minutes(seconds?: number): string {
  return `${Math.round((seconds ?? 0) / 60)} min`;
}

function dateText(value?: string): string {
  if (!value) {
    return "--";
  }
  return new Date(value).toLocaleString();
}

