export async function generateAnalyticsReport(
  analyticsData: AnalyticsOverview,
  options: { deviceName?: string; period?: string } = {},
) {
  const kpis = analyticsData.kpis ?? {
    avgEfficiency: analyticsData.avgEfficiency,
    avgDryingTime: analyticsData.avgDuration,
    avgEnergyPerSession: analyticsData.totalSessions > 0 ? analyticsData.totalEnergyUsed / analyticsData.totalSessions : 0,
    avgMoistureReduction: 0,
    totalGrainDried: 0,
    successRate: analyticsData.totalSessions > 0 ? (analyticsData.completedSessions / analyticsData.totalSessions) * 100 : 0,
  };
  const breakdown = analyticsData.sessionBreakdown ?? {
    completed: analyticsData.completedSessions,
    active: analyticsData.activeSessions,
    aborted: Math.max(0, analyticsData.totalSessions - analyticsData.completedSessions - analyticsData.activeSessions),
  };
  const rows = analyticsData.recentSessions.slice(0, 10).map((session) => `
    <tr>
      <td>${dateText(session.startedAt ?? session.createdAt)}</td>
      <td>${minutes(session.duration)}</td>
      <td>${session.startMoisture}% → ${(session.finalMoisture ?? session.currentMoisture).toFixed(1)}%</td>
      <td>${(session.efficiency ?? 0).toFixed(1)}%</td>
      <td>${(session.efficiency ?? 0) >= 85 ? "A" : (session.efficiency ?? 0) >= 70 ? "B" : (session.efficiency ?? 0) >= 50 ? "C" : "F"}</td>
    </tr>
  `).join("");

  const html = `
    <html><head>${baseStyles()}</head><body>
      <div class="header">
        <div><div class="brand">grAIn</div><div class="muted">Generated by grAIn System</div></div>
        <div><h1>Analytics Report</h1><div class="muted">${escapeHtml(options.period ?? analyticsData.period ?? "Daily")} Report</div></div>
      </div>
      <p class="muted">Generated: ${new Date().toLocaleString()} · Device: ${escapeHtml(options.deviceName ?? analyticsData.deviceId ?? "All Devices")}</p>
      <h2>KPI Summary</h2>
      <div class="grid">
        <div class="box"><div class="muted">Avg Efficiency</div><div class="value">${kpis.avgEfficiency.toFixed(1)}%</div></div>
        <div class="box"><div class="muted">Avg Drying Time</div><div class="value">${kpis.avgDryingTime.toFixed(0)} min</div></div>
        <div class="box"><div class="muted">Avg Energy</div><div class="value">${kpis.avgEnergyPerSession.toFixed(2)} kWh</div></div>
        <div class="box"><div class="muted">Avg Moisture Reduction</div><div class="value">${kpis.avgMoistureReduction.toFixed(1)}%</div></div>
        <div class="box"><div class="muted">Total Grain Dried</div><div class="value">${kpis.totalGrainDried.toFixed(1)} kg</div></div>
        <div class="box"><div class="muted">Success Rate</div><div class="value">${kpis.successRate.toFixed(1)}%</div></div>
      </div>
      <h2>Session Summary</h2>
      <table><tr><th>Completed</th><th>Aborted</th><th>Active</th><th>Success Rate</th></tr>
      <tr><td>${breakdown.completed}</td><td>${breakdown.aborted}</td><td>${breakdown.active}</td><td>${kpis.successRate.toFixed(1)}%</td></tr></table>
      <h2>Best & Worst Session</h2>
      <table><tr><th></th><th>Efficiency</th><th>Duration</th><th>Moisture</th><th>Date</th></tr>
      <tr><td>Best</td><td>${analyticsData.bestSession?.efficiency?.toFixed(1) ?? "--"}%</td><td>${minutes(analyticsData.bestSession?.duration)}</td><td>${analyticsData.bestSession ? `${analyticsData.bestSession.startMoisture}% → ${analyticsData.bestSession.finalMoisture}%` : "--"}</td><td>${dateText(analyticsData.bestSession?.startedAt)}</td></tr>
      <tr><td>Worst</td><td>${analyticsData.worstSession?.efficiency?.toFixed(1) ?? "--"}%</td><td>${minutes(analyticsData.worstSession?.duration)}</td><td>${analyticsData.worstSession ? `${analyticsData.worstSession.startMoisture}% → ${analyticsData.worstSession.finalMoisture}%` : "--"}</td><td>${dateText(analyticsData.worstSession?.startedAt)}</td></tr></table>
      <h2>Recent Sessions</h2>
      <table><tr><th>Date</th><th>Duration</th><th>Moisture</th><th>Efficiency</th><th>Grade</th></tr>${rows || "<tr><td colspan='5'>No recent sessions.</td></tr>"}</table>
      <div class="footer">Generated by grAIn System</div>
    </body></html>
  `;

  const { uri } = await Print.printToFileAsync({ html, base64: false });
  return { uri, filename: `grain-analytics-${Date.now()}.pdf` };
}

function readingStats(readings: SessionReportData["sensorReadings"], key: "temperature" | "humidity" | "moisture" | "fanSpeed") {
  const values = readings.map((reading) => reading[key]).filter(Number.isFinite);
  if (values.length === 0) {
    return "--";
  }
  const min = Math.min(...values).toFixed(1);
  const max = Math.max(...values).toFixed(1);
  const avg = (values.reduce((sum, value) => sum + value, 0) / values.length).toFixed(1);
  return `Min ${min} / Avg ${avg} / Max ${max}`;
}

export async function generateSessionReport(report: SessionReportData) {
  const { session, grainQuality } = report;
  const recommendations = report.predictions.map((prediction) => `<li>${escapeHtml(prediction.recommendation)}</li>`).join("");
  const alerts = report.alerts.map((alert) => `
    <tr><td>${escapeHtml(alert.type)}</td><td>${escapeHtml(alert.message)}</td><td>${alert.severity}</td><td>${dateText(alert.createdAt)}</td></tr>
  `).join("");
  const html = `
    <html><head>${baseStyles()}</head><body>
      <div class="header">
        <div><div class="brand">grAIn</div><div class="muted">Generated by grAIn System</div></div>
        <div><h1>Drying Session Report</h1><div class="muted">${escapeHtml(session.deviceId)}</div></div>
      </div>
      <h2>Session Info</h2>
      <table><tr><th>Device</th><th>Grain Type</th><th>Date</th><th>Duration</th></tr>
      <tr><td>${escapeHtml(session.deviceName)}</td><td>${escapeHtml(session.grainType)}</td><td>${dateText(session.startedAt)}</td><td>${minutes(session.duration)}</td></tr></table>
      <h2>Moisture Journey</h2>
      <div class="box journey">${session.startMoisture.toFixed(1)}% → ${session.finalMoisture.toFixed(1)}%</div>
      <h2>Performance Metrics</h2>
      <table><tr><th>Efficiency</th><th>Energy Used</th><th>Avg Temp</th><th>Avg Humidity</th><th>Avg Fan Speed</th><th>Data Points</th></tr>
      <tr><td>${session.efficiency.toFixed(1)}%</td><td>${session.totalEnergyUsed.toFixed(2)} kWh</td><td>${session.avgTemperature.toFixed(1)} C</td><td>${session.avgHumidity.toFixed(1)}%</td><td>${session.avgFanSpeed.toFixed(0)}%</td><td>${session.dataPoints}</td></tr></table>
      <h2>Grain Quality Assessment</h2>
      <div class="box"><span class="badge grade-${grainQuality.grade}">Grade ${grainQuality.grade}</span>
      <p>Milling recovery estimate: ${grainQuality.millingRecoveryEstimate}%</p>
      <p>Aflatoxin risk: ${grainQuality.aflatoxinRisk}</p>
      <p>${escapeHtml(grainQuality.storageRecommendation)}</p></div>
      <h2>AI Recommendations</h2>
      <ul>${recommendations || "<li>No AI recommendations recorded.</li>"}</ul>
      <h2>Alerts During Session</h2>
      <table><tr><th>Type</th><th>Message</th><th>Severity</th><th>Time</th></tr>${alerts || "<tr><td colspan='4'>No alerts during this session.</td></tr>"}</table>
      <h2>Sensor Readings Summary</h2>
      <table><tr><th>Sensor</th><th>Min / Avg / Max</th></tr>
      <tr><td>Temperature</td><td>${readingStats(report.sensorReadings, "temperature")}</td></tr>
      <tr><td>Humidity</td><td>${readingStats(report.sensorReadings, "humidity")}</td></tr>
      <tr><td>Moisture</td><td>${readingStats(report.sensorReadings, "moisture")}</td></tr>
      <tr><td>Fan Speed</td><td>${readingStats(report.sensorReadings, "fanSpeed")}</td></tr></table>
      <div class="footer">Generated by grAIn System</div>
    </body></html>
  `;
  const { uri } = await Print.printToFileAsync({ html, base64: false });
  return { uri, filename: `grain-session-${session.deviceId}-${Date.now()}.pdf` };
}

export async function shareReport(uri: string, filename: string) {
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, {
      mimeType: "application/pdf",
      dialogTitle: "Share grAIn Report",
      UTI: "com.adobe.pdf",
    });
    return;
  }

  await FileSystem.copyAsync({
    from: uri,
    to: `${FileSystem.documentDirectory}${filename}`,
  });
}
